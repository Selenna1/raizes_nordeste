CREATE TABLE unidades ( 
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  endereco VARCHAR(200),
  telefone VARCHAR(20),
  cidade VARCHAR(100) NOT NULL,
  ativa BOOLEAN NOT NULL
);
CREATE TABLE clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  telefone VARCHAR(20),
  criado_em TIMESTAMP NOT NULL
);
CREATE TABLE produtos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  descricao VARCHAR (255),
  preco NUMERIC(10,2) NOT NULL CHECK(preco >=0),
  categoria VARCHAR(50),
  ativo BOOLEAN NOT NULL
);
CREATE TABLE estoque (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_unidade INTEGER NOT NULL REFERENCES unidades(id),
  id_produto INTEGER NOT NULL REFERENCES produtos(id),
  quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
  UNIQUE (id_unidade, id_produto)
);
CREATE TABLE usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_unidade INTEGER REFERENCES unidades(id),
  id_cliente INTEGER UNIQUE REFERENCES clientes(id),
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  senha VARCHAR(255) NOT NULL,
  perfil VARCHAR(30) NOT NULL CHECK (
    perfil IN ('ADMIN', 'GERENTE', 'ATENDENTE', 'COZINHA', 'CLIENTE')
  ),
  ativo BOOLEAN NOT NULL,
  criado_em TIMESTAMP NOT NULL  
);
CREATE TABLE pedidos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente INTEGER REFERENCES clientes(id),
  id_unidade INTEGER NOT NULL REFERENCES unidades(id),
  canal_pedido VARCHAR(20) NOT NULL CHECK (
    canal_pedido IN ('APP', 'TOTEM', 'BALCAO', 'PICKUP', 'WEB')
  ),
  status VARCHAR(30) NOT NULL CHECK (
    status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'EM_PREPARACAO', 'PRONTO', 'ENTREGUE', 'CANCELADO')
  ),
  valor_total NUMERIC(10,2) NOT NULL CHECK (valor_total >= 0),
  criado_em TIMESTAMP NOT NULL
);
CREATE TABLE itens_pedido (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido INTEGER NOT NULL REFERENCES pedidos(id),
  id_produto INTEGER NOT NULL REFERENCES produtos(id),
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  preco_unitario NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0)
);
CREATE TABLE pagamentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido INTEGER NOT NULL REFERENCES pedidos(id),
  valor NUMERIC(10,2) NOT NULL CHECK (valor >= 0),
  metodo VARCHAR(30) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'ESTORNADO')),
  criado_em TIMESTAMP NOT NULL,
  referencia_gateway VARCHAR(100),
  resposta_gateway VARCHAR(255)
);
CREATE TABLE fidelidade (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente INTEGER NOT NULL UNIQUE REFERENCES clientes(id),
  pontos INTEGER NOT NULL CHECK (pontos >= 0),
  atualizado_em TIMESTAMP NOT NULL,
  consentimento BOOLEAN NOT NULL DEFAULT FALSE,
  data_consentimento TIMESTAMP,
  CHECK (
    (consentimento = FALSE AND data_consentimento IS NULL)
    OR
    (consentimento = TRUE AND data_consentimento IS NOT NULL)
  )
);
CREATE TABLE promocoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  descricao VARCHAR(255),
  tipo_desconto VARCHAR(20) NOT NULL CHECK (tipo_desconto IN ('VALOR_FIXO', 'PERCENTUAL')),
  valor_desconto NUMERIC(10,2) NOT NULL CHECK (valor_desconto >= 0),
  data_inicio TIMESTAMP NOT NULL,
  data_fim TIMESTAMP NOT NULL,
  ativa BOOLEAN NOT NULL,
  CHECK (data_fim >= data_inicio),
  CHECK (tipo_desconto <> 'PERCENTUAL' OR valor_desconto <= 100)
);
CREATE TABLE movimentacoes_estoque (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_unidade INTEGER NOT NULL REFERENCES unidades(id),
  id_produto INTEGER NOT NULL REFERENCES produtos(id),
  id_usuario INTEGER REFERENCES usuarios(id),
  id_pedido INTEGER REFERENCES pedidos(id),
  tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO')),
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  motivo VARCHAR(255),
  criado_em TIMESTAMP NOT NULL
);
CREATE TABLE logs_auditoria (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER REFERENCES usuarios(id),
  acao VARCHAR(100) NOT NULL,
  tabela_afetada VARCHAR(100) NOT NULL,
  id_registro INTEGER,
  detalhes TEXT,
  criado_em TIMESTAMP NOT NULL
);
CREATE TABLE promocoes_produtos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_promocao INTEGER NOT NULL REFERENCES promocoes(id),
  id_produto INTEGER NOT NULL REFERENCES produtos(id),
  UNIQUE (id_promocao, id_produto)
);